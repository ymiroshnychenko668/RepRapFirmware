#!/usr/bin/env python3
"""Extract bounded compatibility profiles from official V3 CAN 1M binaries.

No install/flash actions. Uses Python's standard library only.
"""
import argparse
import hashlib
import json
from pathlib import Path
import zlib

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'src/Modules/CartographerV3'
NAMES = ['CartographerV3_6.1.0_CAN_1M_full_8kib_offset.bin',
         'CartographerV3_6.1.0_CAN_1M_lite_8kib_offset.bin']


def extract(binary):
    matches = []
    for offset, value in enumerate(binary):
        if value != 0x78:
            continue
        try:
            decoder = zlib.decompressobj()
            raw = decoder.decompress(binary[offset:], 65537)
            if not decoder.eof or len(raw) > 65536:
                continue
            dictionary = json.loads(raw)
        except (zlib.error, ValueError, UnicodeDecodeError):
            continue
        if isinstance(dictionary, dict) and {'commands', 'responses', 'config'} <= dictionary.keys():
            size = len(binary) - offset - len(decoder.unused_data)
            matches.append((binary[offset:offset + size], dictionary))
    if len(matches) != 1:
        raise ValueError('expected exactly one identify dictionary')
    return matches[0]


def render(folder):
    lines = ['// Generated by Scripts/cartographer-profiles.py; do not edit.',
             '// Official Cartographer firmware, based on Klipper, GPLv3.',
             '#include "Protocol.h"', 'namespace RrfModules::CartographerV3 {', 'namespace {']
    records, initializers = [], []
    for index, name in enumerate(NAMES):
        binary = (folder / name).read_bytes()
        compressed, dictionary = extract(binary)
        config = dictionary['config']
        assert config['MCU'] == 'stm32f042x6' and config['CANBUS_FREQUENCY'] == 1000000
        assert config['CLOCK_FREQ'] == 48000000 and config['ADC_MAX'] == 4095
        assert config['CARTOGRAPHER_ADC_SMOOTH_COUNT'] == 16
        lines.append(f'constexpr uint8_t Dictionary{index}[] = {{')
        for start in range(0, len(compressed), 20):
            lines.append('    ' + ','.join(f'0x{b:02x}' for b in compressed[start:start + 20]) + ',')
        lines.append('};')
        lines.append(f'constexpr ResponseFormat Responses{index}[] = {{')
        for fmt, msgid in sorted(dictionary['responses'].items(), key=lambda pair: pair[1]):
            params = [part.split('=', 1)[1] for part in fmt.split()[1:]]
            mask = sum(1 << n for n, param in enumerate(params) if param in ('%s', '%*s', '%.*s'))
            assert len(params) <= 8 and msgid < 96
            lines.append(f'    {{{msgid}, {len(params)}, {mask}}}, // {fmt}')
        lines.append('};')
        commands, responses = dictionary['commands'], dictionary['responses']
        def lookup(table, prefix):
            values = [value for key, value in table.items() if key.split()[0] == prefix]
            assert len(values) == 1
            return values[0]
        command_ids = [lookup(commands, n) for n in ('get_config', 'get_uptime', 'cartographer_base_read', 'cartographer_stream', 'get_canbus_id')]
        response_ids = [lookup(responses, n) for n in ('config', 'uptime', 'cartographer_base_data', 'cartographer_data', 'canbus_id', 'starting', 'shutdown', 'is_shutdown')]
        period = 4000 if 'lite' in name else 2000
        initializers.append('    {' + json.dumps(dictionary['version']) + f', Dictionary{index}, sizeof(Dictionary{index}), Responses{index}, sizeof(Responses{index})/sizeof(ResponseFormat), 48000000, 4095, 16, {period}, ' + ', '.join(map(str, command_ids + response_ids)) + '},')
        records.append({'file': name, 'binary_sha256': hashlib.sha256(binary).hexdigest(),
                        'identify_sha256': hashlib.sha256(compressed).hexdigest(), 'identify_bytes': len(compressed),
                        'version': dictionary['version'], 'period_us': period})
    lines += ['}', 'const Profile Profiles[] = {', *initializers, '};',
              'const size_t ProfileCount = sizeof(Profiles)/sizeof(Profile);', '}', '']
    provenance = {'repository': 'https://github.com/Cartographer3D/cartographer_firmware',
                  'commit': 'e5c2b17dbe04ec1f747af5d81b2215949a0a9f8e', 'profiles': records}
    return '\n'.join(lines), json.dumps(provenance, indent=2) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('firmware_directory', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    cpp, metadata = render(args.firmware_directory)
    for name, content in [('Profiles.cpp', cpp), ('profiles.json', metadata)]:
        output = DEST / name
        if args.check:
            if output.read_text() != content:
                raise SystemExit(f'outdated generated profile: {output}')
        else:
            output.write_text(content)
    print('Verified profiles' if args.check else 'Generated profiles')


if __name__ == '__main__':
    main()
